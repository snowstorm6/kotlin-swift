// Make 4: các màn chơi viết dưới dạng text, `#` là tường, `.` là ô trống.
// Thêm màn mới chỉ cần thêm một khối text, Grid.parse lo phần còn lại.

enum Tile { case empty, wall }

struct Level: Sendable {
    let name: String
    let tiles: Grid<Tile>
    let walls: Set<Point>

    init(name: String, text: String) {
        self.name = name
        let tiles = Grid.parse(text) { $0 == "#" ? Tile.wall : .empty }
        self.tiles = tiles
        walls = Set(tiles.points.filter { tiles[$0] == .wall })
    }

